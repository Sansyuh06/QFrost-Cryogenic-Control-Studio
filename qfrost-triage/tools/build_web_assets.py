#!/usr/bin/env python3
"""
tools/build_web_assets.py

Gathers examples/*.qasm3 fixtures, executes Python static scan, extracts golden parity findings
(excluding QWE-002), and generates:
1. web/scanner_data.js (with heavy-hex d=3 graph edges and sample fixtures)
2. web/parity.json (golden findings for node web/test_parity.mjs)

Supports --check flag for CI / freshness verification.
"""

import sys
import os
import glob
import json
import io
import contextlib
from typing import List, Dict, Any

from qiskit.transpiler import CouplingMap
import qiskit.qasm3

# Add repo / qfrost-triage to sys.path
ROOT_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
if ROOT_DIR not in sys.path:
    sys.path.insert(0, ROOT_DIR)

from qfrost.scan import run_scan


def generate_assets():
    examples_dir = os.path.join(ROOT_DIR, "examples")
    fixture_files = sorted(glob.glob(os.path.join(examples_dir, "*.qasm3")))

    # 1. Compute heavy-hex distance 3 edges from Qiskit
    cm = CouplingMap.from_heavy_hex(3)
    hh_edges = sorted([[u, v] for u, v in cm.get_edges()])

    samples = []
    parity_entries = []

    for fpath in fixture_files:
        name = os.path.basename(fpath)
        with open(fpath, "r", encoding="utf-8") as fh:
            text = fh.read()

        py_parse_ok = True
        findings_data = []

        err_buf = io.StringIO()
        try:
            with contextlib.redirect_stderr(err_buf):
                qc = qiskit.qasm3.loads(text)
            report = run_scan(qc, name)
            for f in report.findings:
                if f.id == "QWE-002":
                    continue  # Excluded from parity (web twin uses labeled heuristic)
                findings_data.append({
                    "id": f.id,
                    "severity": f.severity,
                    "score": f.score,
                    "evidence": f.evidence
                })
        except Exception:
            py_parse_ok = False
            findings_data = []

        samples.append({
            "name": name,
            "text": text,
            "py_parse_ok": py_parse_ok
        })

        parity_entries.append({
            "name": name,
            "py_parse_ok": py_parse_ok,
            "findings": findings_data
        })

    scanner_data_obj = {
        "generated_note": "Generated by tools/build_web_assets.py from Qiskit CouplingMap.from_heavy_hex(3)",
        "HH_EDGES": hh_edges,
        "samples": samples
    }

    # Format scanner_data.js
    scanner_data_js = (
        "// Generated by tools/build_web_assets.py — DO NOT EDIT MANUALLY\n"
        "const QFROST_DATA = " + json.dumps(scanner_data_obj, indent=2) + ";\n"
        "if (typeof window !== 'undefined') window.QFROST_DATA = QFROST_DATA;\n"
        "if (typeof globalThis !== 'undefined') globalThis.QFROST_DATA = QFROST_DATA;\n"
    )

    parity_json = json.dumps(parity_entries, indent=2) + "\n"

    return scanner_data_js, parity_json


def main():
    check_mode = "--check" in sys.argv

    scanner_data_js, parity_json = generate_assets()

    web_dir = os.path.join(ROOT_DIR, "web")
    os.makedirs(web_dir, exist_ok=True)
    scanner_data_path = os.path.join(web_dir, "scanner_data.js")
    parity_json_path = os.path.join(web_dir, "parity.json")

    if check_mode:
        if not os.path.exists(scanner_data_path) or not os.path.exists(parity_json_path):
            print("STALE: web/scanner_data.js or web/parity.json does not exist on disk", file=sys.stderr)
            sys.exit(1)

        with open(scanner_data_path, "r", encoding="utf-8") as fh:
            disk_scanner_data = fh.read()
        with open(parity_json_path, "r", encoding="utf-8") as fh:
            disk_parity_json = fh.read()

        if disk_scanner_data != scanner_data_js or disk_parity_json != parity_json:
            print("STALE: Generated web assets differ from files on disk", file=sys.stderr)
            sys.exit(1)

        print("OK: web assets are fresh.")
        sys.exit(0)

    # Write files
    with open(scanner_data_path, "w", encoding="utf-8") as fh:
        fh.write(scanner_data_js)
    with open(parity_json_path, "w", encoding="utf-8") as fh:
        fh.write(parity_json)

    print(f"Generated {scanner_data_path} and {parity_json_path}")


if __name__ == "__main__":
    main()
